import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const url = (source) => `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`;
const fixtureUrl = url(await readFile(new URL('../src/telematics/data/fixtures.js', import.meta.url), 'utf8'));
const source = (await readFile(new URL('../src/telematics/services/mockTelematicsService.js', import.meta.url), 'utf8')).replace('../data/fixtures.js', fixtureUrl);
const { createMockTelematicsService } = await import(url(source));
const { summarizeOwner } = await import(url(await readFile(new URL('../src/telematics/services/ownerSummary.js', import.meta.url), 'utf8')));
const { DRIVER_RESOURCES } = await import(url(await readFile(new URL('../src/telematics/services/driverView.js', import.meta.url), 'utf8')));
const service = createMockTelematicsService({ identity: 'owner:org', audience: 'owner', delayMs: 0 });
const manager = createMockTelematicsService({ identity: 'manager:org', audience: 'manager', delayMs: 0 });
async function snapshot(branchId) {
  const resources = [...DRIVER_RESOURCES, 'adblue'];
  return Object.fromEntries(await Promise.all(resources.map(async (key) => [key, await service.list(key, { branchId })])));
}
const all = summarizeOwner(await snapshot());
const pune = summarizeOwner(await snapshot('pune'));
const mumbai = summarizeOwner(await snapshot('mumbai'));
assert.equal(all.trucks, 5); assert.equal(all.drivers, 3);
for (const key of Object.keys(all)) assert.equal(all[key], pune[key] + mumbai[key], `Branch totals must reconcile: ${key}`);
assert.equal(all.fuelLitres, 300); assert.equal(all.fuelAmount, 27960);
assert.equal(all.adblueLitres, 30); assert.equal(all.adblueAmount, 1950);
assert.equal(all.pendingReviews, 3);
await service.acknowledgeAlert('alert-03');
assert.equal(summarizeOwner(await snapshot()).critical, 0);
await service.review('fuel', 'fuel-02', 'Approved');
assert.equal(summarizeOwner(await snapshot()).pendingReviews, 2);
await service.review('issues', 'issue-02', 'Resolved');
assert.equal(summarizeOwner(await snapshot()).issues, 1);
await assert.rejects(manager.review('fuel', 'fuel-02', 'Approved'), /branch/);
await assert.rejects(service.handoverTruck('driver-01', 'truck-03'), /same demo branch/);
await service.handoverTruck('driver-01', 'truck-05');
assert.equal((await snapshot('pune')).drivers.find((d) => d.id === 'driver-01').vehicleId, 'truck-05');
assert.equal((await manager.list('drivers', { branchId: 'pune' }))[0].vehicleId, 'truck-01');
service.reset();
assert.equal(summarizeOwner(await snapshot()).pendingReviews, 3);
service.setScenario('empty');
assert.equal(summarizeOwner(await snapshot()).trucks, 0);
assert.equal(summarizeOwner(null).fuelAmount, 0);
service.dispose(); manager.dispose();
console.log('Owner checks passed: branch totals reconcile, summary updates, scoped reviews/handovers, session isolation, reset and empty state.');
