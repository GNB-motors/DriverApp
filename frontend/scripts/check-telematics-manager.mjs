import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const url = (source) => `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`;
const fixtureUrl = url(await readFile(new URL('../src/telematics/data/fixtures.js', import.meta.url), 'utf8'));
const source = (await readFile(new URL('../src/telematics/services/mockTelematicsService.js', import.meta.url), 'utf8')).replace('../data/fixtures.js', fixtureUrl);
const { createMockTelematicsService } = await import(url(source));
const make = () => createMockTelematicsService({ identity: 'manager:org', audience: 'manager', delayMs: 0 });
const service = make();
const independent = make();
const pune = { branchId: 'pune' }; const mumbai = { branchId: 'mumbai' };
assert.equal((await service.list('vehicles', pune)).length, 3);
assert.equal((await service.list('vehicles', mumbai)).length, 2);
assert.equal((await service.list('drivers', pune)).length, 2);
assert.equal((await service.list('drivers', mumbai)).length, 1);
assert.equal((await service.list('documents', pune)).length, 2); // Includes personal licence.
assert.equal((await service.list('documents', mumbai)).length, 1);
assert.deepEqual((await service.list('alerts', mumbai)).map((a) => a.id), ['alert-02']);
await assert.rejects(service.acknowledgeAlert('alert-02', pune), /branch/);
await service.acknowledgeAlert('alert-02', mumbai);
assert.equal((await service.list('alerts', mumbai))[0].acknowledged, true);
assert.equal((await independent.list('alerts', mumbai))[0].acknowledged, false);
await assert.rejects(service.handoverTruck('driver-01', 'truck-02', pune), /Confirm/);
assert.equal((await service.list('drivers', pune))[0].vehicleId, 'truck-01');
await assert.rejects(service.handoverTruck('driver-01', 'truck-03', pune), /branch/);
const handover = await service.handoverTruck('driver-01', 'truck-02', { ...pune, confirmDisplacement: true });
assert.equal(handover.displacedDriverId, 'driver-02');
let vehicles = await service.list('vehicles', pune); let drivers = await service.list('drivers', pune);
assert.equal(vehicles.find((v) => v.id === 'truck-01').driverId, null);
assert.equal(vehicles.find((v) => v.id === 'truck-02').driverId, 'driver-01');
assert.equal(drivers.find((d) => d.id === 'driver-02').vehicleId, null);
assert.equal(drivers.find((d) => d.id === 'driver-01').vehicleId, 'truck-02');
await service.handoverTruck('driver-02', 'truck-05', pune);
assert.equal((await service.list('drivers', pune)).find((d) => d.id === 'driver-02').vehicleId, 'truck-05');
await assert.rejects(service.review('fuel', 'fuel-02', 'Approved', pune), /branch/);
await assert.rejects(service.review('fuel', 'fuel-01', 'Rejected', pune), /reason/);
await service.review('fuel', 'fuel-01', 'Rejected', { ...pune, note: 'Sample slip is unreadable' });
assert.equal((await service.list('fuel', pune))[0].reviewNote, 'Sample slip is unreadable');
await assert.rejects(service.review('fuel', 'fuel-01', 'Approved', pune), /already/);
await service.review('bills', 'bill-01', 'Approved', pune);
assert.equal((await service.list('bills', pune))[0].status, 'Approved');
await service.review('issues', 'issue-01', 'In progress', pune);
await service.review('issues', 'issue-01', 'Resolved', pune);
await assert.rejects(service.review('issues', 'issue-01', 'In progress', pune), /resolved/);
await assert.rejects(service.review('unknown', 'anything', 'Approved', pune), /Invalid/);
service.reset();
assert.equal((await service.list('bills', pune))[0].status, 'Pending review');
assert.equal((await service.list('drivers', pune))[0].vehicleId, 'truck-01');
service.setScenario('empty');
assert.deepEqual(await service.list('vehicles', pune), []);
service.reset(); service.dispose(); independent.dispose();
console.log('Manager checks passed: branch-filtered records, guarded local actions, handover/displacement consistency, review transitions, isolation and reset.');
