import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
// Data URLs allow this check to run without changing the Expo package's module type.
const url = (source) => `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`;
const fixtures = url(await readFile(new URL('../src/telematics/data/fixtures.js', import.meta.url), 'utf8'));
const source = (await readFile(new URL('../src/telematics/services/mockTelematicsService.js', import.meta.url), 'utf8')).replace('../data/fixtures.js', fixtures);
const { createMockTelematicsService } = await import(url(source));
const now = Date.parse('2026-10-23T06:00:00Z');
const make = (identity) => createMockTelematicsService({ identity, now, delayMs: 0 });
const first = make('user-a:org-a');
const second = make('user-b:org-b');
assert.throws(() => createMockTelematicsService(), /identity/);
const trucks = await first.list('vehicles');
trucks[0].plate = 'changed outside service';
assert.equal((await first.list('vehicles'))[0].plate, 'MH 12 AB 4821');
await first.acknowledgeAlert('alert-01');
assert.equal((await first.list('alerts'))[0].acknowledged, true);
assert.equal((await second.list('alerts'))[0].acknowledged, false);
await assert.rejects(first.assignTruck('driver-01', 'truck-02'), /already assigned/);
await first.assignTruck('driver-01', 'truck-03');
assert.equal((await first.list('vehicles')).find((v) => v.id === 'truck-01').driverId, null);
assert.equal((await first.list('drivers'))[0].vehicleId, 'truck-03');
assert.equal((await first.list('alerts', { branchId: 'mumbai' })).length, 1);
first.setScenario('phoneFallback');
assert.equal((await first.list('vehicles'))[0].source, 'phone');
first.setScenario('staleGps');
assert.equal(now - Date.parse((await first.list('vehicles'))[0].updatedAt), 95 * 60000);
first.setScenario('unassigned');
assert.equal((await first.list('drivers'))[0].vehicleId, null);
assert.equal((await first.list('vehicles')).filter((v) => v.driverId === 'driver-01').length, 0);
first.setScenario('empty');
assert.deepEqual(await first.list('vehicles'), []);
first.setScenario('error');
await assert.rejects(first.list('vehicles'), /interrupted/);
first.reset();
await assert.rejects(first.submit('fuel', { vehicleId: 'truck-01', litres: -1, amountInr: 100 }), /positive/);
await first.submit('issues', { vehicleId: 'truck-01', title: 'Sample tyre issue' });
assert.equal((await first.list('issues')).length, 2);
assert.equal((await second.list('issues')).length, 1);
assert.equal((await first.list('alerts'))[0].acknowledged, false);
assert.equal((await first.list('drivers'))[0].vehicleId, 'truck-01');
const pending = first.list('vehicles');
first.dispose();
await assert.rejects(pending, /ended/);
assert.equal((await second.list('vehicles')).length, 3);
console.log('Telematics foundation checks passed: isolation, mutations, branch filtering, scenarios, reset and session disposal.');
